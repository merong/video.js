// Read-only: real mouse click + keyboard typing into the mid-roll skip wait field (no save).
import { BASE, launch, newContext, login, save, sleep, shot } from './lib.mjs';
const browser = await launch();
const context = await newContext(browser, { height: 1000 });
const page = await context.newPage();
await login(page);
await page.goto(`${BASE}/#/schedule`);
await page.getByRole('button', { name: '편성 불러오기' }).click();
await sleep(1000);
const editor = page.getByRole('form', { name: '광고 편성 편집' });
await editor.getByLabel('이 대상의 광고', { exact: true }).selectOption({ label: '직접 편성 · 전체 대체' });
const add = editor.getByRole('group', { name: '광고 구간 추가' });
const mid = editor.getByRole('article', { name: /미드롤/ });
const active = () => page.evaluate(() => ({ tag: document.activeElement?.tagName, label: document.activeElement?.labels?.[0]?.textContent ?? document.activeElement?.textContent?.slice(0, 20) ?? null, value: document.activeElement?.value ?? null }));
const out = {};
await add.getByRole('button', { name: '미드롤' }).click();
const pos = mid.getByLabel('본편 재생 위치 (초)', { exact: true });
await pos.click();
await page.keyboard.press('ControlOrMeta+A');
await page.keyboard.type('5');
out.afterTypePos = { active: await active(), pos: await pos.inputValue() };
await mid.getByLabel('추가할 소재', { exact: true }).selectOption({ label: 'QA 생수 미드롤 · v1 · 영상' });
await mid.getByRole('button', { name: '광고 추가' }).click();
out.afterAddClick = await active();
await sleep(500);
out.afterAddClick500 = await active();
const skip = mid.getByLabel('이 광고의 스킵', { exact: true });
await skip.selectOption({ label: 'N초 후 현재 광고만 스킵' });
out.afterSelect = await active();
const wait = mid.getByLabel('스킵 대기 (초)', { exact: true });
await wait.click();
out.afterWaitClick = await active();
await sleep(300);
out.afterWaitClick300 = await active();
await page.keyboard.press('ControlOrMeta+A');
await page.keyboard.type('3');
await sleep(300);
out.afterTypeWait = { active: await active(), pos: await pos.inputValue(), wait: await wait.inputValue() };
// Also check: does typing in the pre-roll fields keep focus when no mid-roll exists? Reference only.
await shot(page, 'B06/probe-mid2.png', { fullPage: true });
save('B06/probe-mid2.json', out);
console.log(JSON.stringify(out, null, 1));
await browser.close();
