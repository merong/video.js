// Install groups whose row names repeat in other groups (`media`, `preset`) get their own anchor prefix.
const anchorPrefixes = { mount: 'mount-', events: 'event-', exampleQuery: 'query-' };

/**
 * `opt-<name>` for an install option row: leading `--` removed, lowercased, only `a-z`, `0-9` and `-` kept. Must
 * match `optionAnchor` in `ui/src/player/help-anchors.ts`.
 */
export function optionAnchor(name, group) {
  const slug = name
    .replace(/^--/, '')
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, '');

  return `opt-${anchorPrefixes[group] ?? ''}${slug}`;
}

/** `field-<path>` for a preset field, dots as `-`. Must match `fieldAnchor` in `ui/src/player/help-anchors.ts`. */
export function fieldAnchor(path) {
  return `field-${path.replaceAll('.', '-')}`;
}

// Stages the player applies: A2-1, the ad skin's seek buttons and captions switch (ads-a2e-spec 3) and the lecture
// group (ads-lms-spec 2).
const appliedStages = ['A2-1', 'A2-E', 'L-2'];

/** Stage text for a preset field (contract A2-D 4). */
export function stageText(stage) {
  return appliedStages.includes(stage) ? '적용' : `준비 중(${stage})`;
}

/** What a preset field accepts, as help text. */
export function acceptsText(accepts) {
  const unit = accepts.unit ?? '';

  switch (accepts.kind) {
    case 'boolean':
      return 'true | false';
    case 'enum':
      return accepts.values.join(' | ');
    case 'step':
      return accepts.values.map((value) => `${value}${unit}`).join(' | ');
    case 'integer':
      return `${accepts.min}–${accepts.max}${unit} 정수`;
    case 'color':
      return accepts.alpha ? '#rrggbb 또는 투명도를 더한 #rrggbbaa(소문자)' : '#rrggbb(소문자)';
    case 'url':
      return 'http(s):// 주소';
    case 'text':
      return accepts.placeholders
        ? `${accepts.max}자 이하, 자리표시자 ${accepts.placeholders.join(' ')}`
        : `${accepts.max}자 이하`;
    default:
      return '아직 받지 않음';
  }
}

